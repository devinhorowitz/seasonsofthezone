@case
def t_a_ghoul_config_is_repaired_on_save():
    """The two mistakes from the Discord thread: the table thrown away by an empty one
    below it, and ("summer,spring")."""
    with tempfile.TemporaryDirectory() as d:
        install(d, config=GHOUL)
        rc, out = run(d, "status", tool="season.py")
        assert rc != 0, "the broken file was accepted as it is"
        rc, out = run(d, "list")
        assert "saving removes that line" in out and "right shape" in out, out
        rc, out = run(d, "add", "Lonely Mod", "--when", "spring")
        assert rc == 0, out
        t, _ = table(d)
        assert t["Map Pack"]["when"] == ("summer", "spring"), t
        assert set(t) == {"Winter Pack", "Map Pack", "Lonely Mod"}, t
        assert config(d).count("TOGGLE_MODS =") == 1, "the empty table is still there"
        accepted(d)
    return "one TOGGLE_MODS left, (\"summer\", \"spring\"), and season.py accepts it"


@case
def t_a_file_python_cannot_read_is_left_alone():
    bad = HAND.replace('("winter", "winter_snow")', '(, "winter_snow")')
    with tempfile.TemporaryDirectory() as d:
        install(d, config=bad)
        rc, out = run(d, "add", "Map Pack", "--when", "summer")
        assert rc == 1 and "can't be read" in out and "line 9" in out, out
        assert config(d) == bad, "an unreadable file was overwritten"
    return "refused, with the line, and the file untouched"


@case
def t_the_window_edits_and_saves():
    """The window, driven the way a click would, in a process of its own."""
    driver = r'''
import sys
sys.path.insert(0, sys.argv[1])
import tkinter as tk
import config_edit as ce
import configure
root = tk.Tk()
root.withdraw()
cal, inst = ce.Calendar(), ce.Install()
app = configure.App(root, cal, inst)
app.select("Winter Pack")
app.set_when("Winter Pack", ["winter", "winter_snow"])
app.add_event("halloween", (10, 31), (10, 31))
app.select("Map Pack")
app.set_when("Map Pack", ["summer"])
app.set_when("Map Pack", [])
print("dirty before", cal.dirty())
print("saved", app.save(quiet=True))
print("dirty after", cal.dirty())
root.destroy()
'''
    with tempfile.TemporaryDirectory() as d:
        install(d)
        p = os.path.join(d, "drive.py")
        io.open(p, "w", encoding="utf-8").write(driver)
        r = subprocess.run([sys.executable, p, os.path.join(d, "_tools")], cwd=d,
                           capture_output=True, text=True)
        out = r.stdout + r.stderr
        assert r.returncode == 0 and "saved True" in out, out
        assert "dirty before True" in out and "dirty after False" in out, out
        t, e = table(d)
        assert set(t) == {"Winter Pack"}, "unticking everything did not take it off: %s" % t
        assert t["Winter Pack"] == {"when": ("winter", "winter_snow", "halloween"),
                                    "above": "Grass Compat"}, t
        assert e == {"halloween": ((10, 31), (10, 31))}, e
        accepted(d)
    return "ticks, a new event and an untick saved; season.py accepts the file"


@case
def t_a_real_config_comes_back_unchanged():
    """The live install's config, loaded and written back with nothing changed."""
    live = os.path.join(os.environ.get("GAMMA_INSTALL", r"D:\GAMMA"), "_tools",
                        "seasons_config.py")
    if not os.path.isfile(live):
        return "no live config here - skipped"
    sys.path.insert(0, HERE)
    import config_edit as ce
    cal = ce.Calendar(live)
    assert not cal.error and not cal.dirty(), (cal.error, cal.fixes)
    text, kept = cal.render()
    assert kept and text.replace("\n", cal.nl) == cal.original, "a no-op save changes it"
    return "%d entries, byte for byte" % len(cal.toggle)


if __name__ == "__main__":
    print("  running the shipped configure.py against scratch installs")
    bad = 0
    for fn in CASES:
        try:
            print("  PASS  %-48s %s" % (fn.__name__[2:], fn()))
        except AssertionError as e:
            bad += 1
            print("  FAIL  %-48s %s" % (fn.__name__[2:], e))
        except Exception as e:
            bad += 1
            print("  ERROR %-48s %s: %s" % (fn.__name__[2:], type(e).__name__, e))
    print("\n  %d/%d passed" % (len(CASES) - bad, len(CASES)))
    sys.exit(1 if bad else 0)
