@case
def t_the_game_reads_every_rule_as_season_py_does():
    """Every day of 2026 to 2028, a leap year among them: the game's event rules and windows
    agree with season.py's event_on() on each, for each kind of rule there is."""
    specs = {
        "w": ((12, 24), (12, 26)), "wrap": ((12, 26), (1, 6)), "leap": ((2, 28), (3, 1)),
        "wk": {"weekdays": ("sat", "sun")}, "pay": {"days": (1, 15, -1)},
        "first_mon": {"weekdays": ("mon",), "weeks": (1,)},
        "last_fri": {"weekdays": ("fri",), "weeks": (-1,)},
        "f13": {"weekdays": ("fri",), "days": (13,)},
        "winter_wk": {"weekdays": ("sat", "sun"), "within": ((12, 1), (2, 28))},
        "months": {"months": (12, 1, 2), "days": (-2,)},
    }
    text, keys = calendar(own={}, events=specs, periods={}, spells={})
    lua, g = tcal.build(2026, 1, 1, calendar=text)
    yours, item_on = tcal.probe(lua, g, "YOURS", "item_on")
    events = {yours.events[i].name: yours.events[i] for i in range(1, len(yours.events) + 1)}
    assert set(events) == set(specs), sorted(events)
    day_of = lua.eval("function(y, m, d) local t = os.date('*t', os.time({year = y, "
                      "month = m, day = d, hour = 12})) t.iso = string.format("
                      "'%04d-%02d-%02d', y, m, d) return t end")
    day, checked, on = datetime.date(2026, 1, 1), 0, 0
    while day.year <= 2028:
        t = day_of(day.year, day.month, day.day)
        for name, spec in specs.items():
            want = season.event_on(day, spec)
            got = bool(item_on(events[name], t, None))
            assert got == want, "%s on %s: game %s, season.py %s" % (name, day, got, want)
            checked += 1
            on += want
        day += datetime.timedelta(days=1)
    return "%d rule-days over 3 years agree, %d of them on" % (checked, on)


