# One of each, and two kinds of event rule. Saturday 17 October 2026 is in autumn, inside
# Hunter's moon and a weekend, two weeks before Halloween and the turn to winter.
OWN = {"Hunter's moon": ((10, 10), (10, 31)), "Wormhole season": ((8, 1), (8, 31))}
EVENTS = {"christmas": ((12, 24), (12, 26)), "halloween": ((10, 31), (10, 31)),
          "weekend": {"weekdays": ("sat", "sun")}, "twelvetide": ((12, 26), (1, 6))}
PERIODS = {"high_summer": (7, 1)}
SPELLS = {"Indian summer": {"in": ("autumn",), "chance": 2, "days": (2, 4), "as": "summer"},
          "Odd fog": {"in": ("autumn", "Hunter's moon"), "chance": 0.5, "days": 1,
                      "as": None}}


def tables(own=OWN, events=EVENTS, periods=PERIODS, spells=SPELLS):
    """season.py's tables set to these for a `with`, and put back after"""
    class Swap(object):
        def __enter__(self):
            self.saved = (season.OWN_SEASONS, season.EVENTS, season.PERIODS, season.SPELLS)
            season.OWN_SEASONS, season.EVENTS = own, events
            season.PERIODS, season.SPELLS = periods, spells
            return season

        def __exit__(self, *a):
            (season.OWN_SEASONS, season.EVENTS, season.PERIODS,
             season.SPELLS) = self.saved
    return Swap()


def calendar(today=None, spell=None, roll=None, **kw):
    """season_calendar.ltx as season.py writes it, Polesia's calendar and the player's own
    from `kw` (the tables above unless given): with `spell`, (season, name, first, last),
    its [spell]; `roll`, (season, draw, chance), its [roll]; and `today`, (day,
    [(name, first, last, as)], [weather kinds]), its [today]. Returns the text and
    season.py's keys."""
    with tables(**kw) as s:
        lines = ["; generated by _tools/season.py from seasons_config.py - do not edit by hand",
                 "[calendar]", "custom = false", "dial = default"] + s.your_sections()
        keys = s.your_keys()
    if spell:
        lines += ["", "[spell]", "season = %s" % spell[0], "name = %s" % spell[1],
                  "first = %s" % spell[2], "last = %s" % spell[3]]
    if roll:
        lines += ["", "[roll]", "season = %s" % roll[0], "draw = %d" % roll[1],
                  "chance = %d" % roll[2], "day = 2026-10-17"]
    if today:
        day, on, weather = today
        lines += ["", "[today]", "day = %s" % day]
        if weather:
            lines.append("weather = %s" % ", ".join(weather))
        for i, (name, first, last, brings) in enumerate(on, 1):
            lines += ["%d_spell = %s" % (i, name), "%d_key = %s" % (i, keys[("spell", name)]),
                      "%d_first = %s" % (i, first), "%d_last = %s" % (i, last)]
            if brings:
                lines.append("%d_as = %s" % (i, brings))
    return CRLF.join(lines) + CRLF, keys


ROW_SETUP = """
function make_rows(p, n1, n2, heads)
    p.heads = {}
    for i = 1, heads do p.heads[i] = mkwidget() end
    p.rows, p.used, p.cursor = {}, {}, {}
    for col = 1, 2 do
        p.rows[col] = {}
        for i = 1, (col == 1 and n1 or n2) do
            p.rows[col][i] = {mkwidget(), mkwidget(), mkwidget()}
        end
        p.used[col], p.cursor[col] = 0, 0
    end
    p.head_n = 0
end
"""


def filled(lua, g):
    """The page's Fill(), with every widget it writes to, as InitControls makes them. Returns
    the page, and what it shows: {"header", "status", "rows": [(col, [texts], rgb, glows)],
    "heads": [texts]}."""
    lua.execute(ROW_SETUP)
    bars = lua.table_from([g.mkwidget() for _ in range(tcal.BAR_POOL)])
    axis = lua.table_from([g.mkwidget() for _ in range(5)])
    months = lua.table_from([g.mkwidget() for _ in range(12)])
    p = g.make_page(g.SeasonsPDA, bars, axis, months)
    for name in ("header", "bar", "subheader", "turning", "dial", "dial_caption",
                 "grid_cap_l", "grid_cap_r"):
        p[name] = g.mkwidget()
    g.make_rows(p, 12, 12, 4)
    g.SeasonsPDA.Fill(p)
    # a Lua table crosses into Python as a new wrapper each time, so whether a widget is
    # on the glow list is asked on the Lua side
    glows = lua.eval("function(p, w) for _, x in ipairs(p.glow or {}) do "
                     "if rawequal(x, w) then return true end end return false end")
    rows = []
    for col in (1, 2):
        for i in range(1, 13):
            s = p.rows[col][i]
            ws = [s[f] for f in (1, 2, 3) if s[f].vis]
            if ws:
                c = ws[0].col
                rows.append((col, [w.text for w in ws], (c["r"], c["g"], c["b"]),
                             any(glows(p, w) for w in ws)))
    heads = [p.heads[i].text for i in range(1, 5) if p.heads[i].vis]
    return p, {"header": p.header.text, "status": p.turning.text, "rows": rows,
               "heads": heads, "status_glows": glows(p, p.turning), "bar": p.bar.tex}


def page_data(day=(2026, 10, 17), mcm=None, **kw):
    text, keys = calendar(**kw)
    lua, g = tcal.build(*day, calendar=text, mcm=mcm)
    return lua, g, g.zzz_seasons_of_the_zone.calendar_page(), keys


def items(t):
    return [t[i] for i in range(1, len(t) + 1)] if t else []


