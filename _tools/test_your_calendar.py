@case
def t_the_grid_draws_the_player_s_own_and_glows_what_is_on():
    """A line over the days of each season of the player's own, dated event and period:
    Hunter's moon on, glowing over a halo; the rest dim. Weekly rules are not drawn."""
    lua, g, d, _ = page_data()
    marks = sorted((m["from"], m["to"], bool(m.active)) for m in items(d.marks))
    doy = lambda m, dd: datetime.date(2026, m, dd).timetuple().tm_yday  # noqa: E731
    want = sorted([(doy(10, 10), doy(10, 31), True), (doy(8, 1), doy(8, 31), False),
                   (doy(12, 24), doy(12, 26), False), (doy(10, 31), doy(10, 31), False),
                   (doy(12, 26), 365, False), (1, doy(1, 6), False),
                   (doy(7, 1), doy(9, 14), False)])
    assert marks == want, marks
    p, shown = filled(lua, g)
    bars = [p.bars[i] for i in range(1, tcal.BAR_POOL + 1) if p.bars[i].vis]
    lines = [b for b in bars if int(b.h) == OVER_H]
    lit = [p.glow_bars[i] for i in range(1, len(p.glow_bars) + 1)]
    halos = [p.halos[i] for i in range(1, len(p.halos) + 1)]
    # Hunter's moon is one run in October; its line sits in the gap above the row
    assert len(lit) == 1 and len(halos) == 1, (len(lit), len(halos))
    oct_y = ROW_Y0 + 9 * PITCH
    assert (int(lit[0].x), int(lit[0].y), int(lit[0].w)) == (
        GUT + 9 * CELL_W, oct_y - 3, 22 * CELL_W - 1), (lit[0].x, lit[0].y, lit[0].w)
    assert int(halos[0].h) == HALO_H and int(halos[0].y) == oct_y - HALO_H
    # a line for each month a window touches: Aug, Oct twice, Dec, Jan, Jul to Sep
    assert len(lines) == 9, len(lines)
    assert all(int(b.y) % PITCH == (ROW_Y0 - 3) % PITCH for b in lines), \
        "a line is not in the gap above a row"
    # the glow moves: two moments, two colours, on the line and the rows that are on
    cols = []
    for ms in (0, 500):
        g.time_global = lambda ms=ms: ms
        g.SeasonsPDA.Update(p)
        cols.append((lit[0].col["r"], lit[0].col["g"], lit[0].col["b"], halos[0].col["a"]))
    assert cols[0] != cols[1], "the glow stands still: %s" % cols
    return "7 spans, Hunter's moon lit over a halo, 9 lines in the gaps; the glow moves"


