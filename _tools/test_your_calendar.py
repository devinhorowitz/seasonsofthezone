def t_play_bat_hands_the_player_s_own_to_the_game():
    """season.py apply writes them into season_calendar.ltx, and the labels of their MCM
    switches in English and Russian; a configure.bat change hands them over too. With none,
    both files are the stubs the release ships."""
    config = ("OWN_SEASONS = %r\nEVENTS = %r\nPERIODS = %r\nSPELLS = %r\n"
              % (OWN, EVENTS, PERIODS, SPELLS))
    with tempfile.TemporaryDirectory() as d:
        tc.install(d, config=config)
        cal, _ = tc.with_mod(d)
        text_dir = os.path.join(os.path.dirname(cal), "text")
        os.makedirs(text_dir)
        rc, out = tc.run(d, "apply", tool="season.py",
                         env=dict(os.environ, PYTHONIOENCODING="utf-8"))
        assert rc == 0, out
        body = io.open(cal, encoding="cp1251").read()
        for part in ("[own]", "1_name = Wormhole season", "2_name = Hunter's moon",
                     "[events]", "4_weekdays = sat, sun", "[periods]", "1_from = 07-01",
                     "[spells]", "1_in = autumn", "2_chance = 0.5", "2_in = autumn, Hunter's moon"):
            assert part in body, (part, body)
        with tables() as s:
            keys = s.your_keys()
        for lang in ("eng", "rus"):
            xml = io.open(os.path.join(text_dir, lang, season.YOURS_XML), encoding="cp1251").read()
            for (kind, name), key in keys.items():
                assert 'id="ui_mcm_seasons_zone_ann_%s"' % key in xml, (lang, key)
            assert ("&quot;" not in xml) and ("Hunter's moon" in xml), xml[:400]

    # a change made in configure.bat reaches the game without play.bat
    with tempfile.TemporaryDirectory() as d:
        tc.install(d, config="")
        cal, _ = tc.with_mod(d)
        os.makedirs(os.path.join(os.path.dirname(cal), "text"))
        rc, out = tc.run(d, "event", "christmas", "12-24", "12-26")
        assert rc == 0, out
        body = io.open(cal, encoding="cp1251").read()
        assert "[events]" in body and "1_name = christmas" in body, body

    # none: the stubs, byte for byte
    with tempfile.TemporaryDirectory() as d:
        tc.install(d, config="")
        cal, _ = tc.with_mod(d)
        text_dir = os.path.join(os.path.dirname(cal), "text")
        os.makedirs(text_dir)
        rc, out = tc.run(d, "apply", tool="season.py",
                         env=dict(os.environ, PYTHONIOENCODING="utf-8"))
        assert rc == 0, out
        assert io.open(cal, encoding="cp1251", newline="").read() == \
            build_release.STUB_CALENDAR
        for lang in ("eng", "rus"):
            got = io.open(os.path.join(text_dir, lang, season.YOURS_XML), encoding="cp1251",
                          newline="").read()
            assert got == build_release.STUB_YOURS, (lang, got)
    shipped = [os.path.join(tcal.SCRIPTS, "..", "configs", "text", lang, season.YOURS_XML)
               for lang in ("eng", "rus")]
    assert all(io.open(p, encoding="cp1251", newline="").read() == build_release.STUB_YOURS
               for p in shipped), "the repo's stubs are not the release's"
    return "4 sections and %d labels in 2 languages; configure hands an event over; stubs" % (
        len(keys))


