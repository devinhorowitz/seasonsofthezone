def t_silence_drops_every_message():
    """MCM's "PDA notifications" off, which the Silence button on the app's pages writes: the
    greeting, the player's own and a turn while playing all go unsent, whatever their own
    switches say, and the log names each one dropped. Asked at sending time, so a message
    queued before the switch went off is dropped too."""
    text, _ = calendar(spell=("summer", "Indian summer", "2026-10-16", "2026-10-19"),
                       today=("2026-10-17", [("Indian summer", "2026-10-16", "2026-10-19",
                                              "summer")], []))
    sent = []
    mcm = {"seasons_zone/main/blend_days": 0, "seasons_zone/main/pda_news": False}
    lua, g = tcal.build(2026, 10, 17, calendar=text, mcm=mcm)
    queued = []
    g.CreateTimeEvent = lambda ev, act, delay, fn, *a: queued.append(fn)
    g.news_manager = lua.table_from({"send_tip": lambda a, msg, *r: sent.append(msg)})
    (announce,) = tcal.probe(lua, g, "pda_announce")
    announce()
    g.zzz_seasons_of_the_zone.announce_yours(0, True)
    for fn in queued:
        fn()
    assert sent == [], sent
    dropped = [l for l in tcal.LOG if "(silenced)" in l]
    assert len(dropped) == 3, tcal.LOG
    # on again: the same three go out; queued while on and silenced before they fire: dropped
    mcm["seasons_zone/main/pda_news"] = True
    del queued[:]
    announce()
    g.zzz_seasons_of_the_zone.announce_yours(0, True)
    for fn in queued:
        fn()
    assert len(sent) == 3, sent
    del sent[:], queued[:]
    g.zzz_seasons_of_the_zone.announce_yours(0, True)
    mcm["seasons_zone/main/pda_news"] = False
    for fn in queued:
        fn()
    assert queued and sent == [], (len(queued), sent)
    return "silenced, 3 messages dropped and logged; on again, 3 sent; queued, then dropped"


@case
def t_a_turn_while_playing_is_told():
    """The day moves on while playing: a message as winter draws near, another as it comes,
    the ground's at the next launch since autumn is staged, and one as a season of the
    player's own begins. None at the first look, none twice, none with the season pinned,
    and none with MCM's switch off."""
    text, keys = calendar()

    def play(dates, mcm=None, staged=None):
        lua, g = tcal.build(2026, 10, 8, calendar=text, mcm=mcm,
                            staged=staged or {"season": "autumn", "staging": "on"})
        lua.execute(tcal.CLOCK)
        clock = g.clock_os()
        g.os = clock
        sent = []
        g.CreateTimeEvent = lambda ev, act, delay, fn, *a: fn()
        g.news_manager = lua.table_from({"send_tip": lambda a, msg, *r: sent.append(msg)})
        out = []
        for m, d in dates:
            clock.set(2026, m, d)
            del sent[:]
            g.zzz_seasons_of_the_zone.turn_tick()
            out.append(list(sent))
        return out

    # Thursday the 8th, Saturday the 10th, a Sunday, the next Sunday and Monday, Sunday
    # the 1st and the Monday after: the weekend begins twice, and is told as it does
    days = [(10, 8), (10, 10), (10, 11), (10, 25), (10, 26), (11, 1), (11, 2)]
    got = play(days)
    assert got == [[],
                   ["Hunter's moon comes to the Zone, until October 31, 2026.",
                    "Weekend comes to the Zone, until October 11, 2026."],
                   [],
                   ["Winter is near: it reaches the Zone in 7 days."],
                   [],
                   ["Winter has come to the Zone. Its ground follows at the next launch "
                    "through play.bat.", "Weekend comes to the Zone today."],
                   []], got
    # with winter staged already there is no ground to wait for
    got = play([(10, 31), (11, 1)], staged={"season": "winter", "staging": "on"})
    assert got[1] == ["Winter has come to the Zone."], got
    # a pin fixes the season: the moon still begins, no turn is told
    got = play(days, mcm={"seasons_zone/main/mode": "summer"})
    assert [m for m in sum(got, []) if "Weekend" not in m] == [
        "Hunter's moon comes to the Zone, until October 31, 2026."], got
    # MCM's switches off: neither the turn nor the moon nor the weekend
    got = play(days, mcm={"seasons_zone/main/pda_turns": False,
                          "seasons_zone/yours/ann_" + keys[("own", "Hunter's moon")]: False,
                          "seasons_zone/yours/ann_" + keys[("event", "weekend")]: False})
    assert sum(got, []) == [], got
    return "the moon, winter near, winter come with its ground; quiet when pinned or off"


@case
def t_mcm_has_a_switch_for_each_of_the_player_s_own():
    """Your calendar: a heading for each kind and a switch for each one, on by default, by
    the key season.py gives it; no page for a player with none."""
    text, keys = calendar()
    lua, g = tcal.build(2026, 7, 1, calendar=text)
    src = io.open(os.path.join(tcal.SCRIPTS, "zzz_seasons_of_the_zone_mcm.script"),
                  encoding="utf-8").read()
    op = g.load_in(src, "zzz_seasons_of_the_zone_mcm", g).on_mcm_load()
    pages = {op.gr[i].id: op.gr[i] for i in range(1, len(op.gr) + 1)}
    assert "yours" in pages and pages["yours"].text == "ui_mcm_seasons_zone_page_yours"
    opts = [pages["yours"].gr[i] for i in range(1, len(pages["yours"].gr) + 1)]
    checks = [(o.id, o.hint, o["def"]) for o in opts if o.type == "check"]
    want = []
    for kind, table in (("own", OWN), ("event", EVENTS), ("period", PERIODS),
                        ("spell", SPELLS)):
        ordered = (sorted(table, key=lambda n: (tuple(table[n][0]), n.casefold()))
                   if kind == "own" else sorted(table, key=lambda n: (n.casefold(), n))
                   if kind != "period" else sorted(table, key=lambda n: tuple(table[n])))
        want += [("ann_" + keys[(kind, n)], "seasons_zone_ann_" + keys[(kind, n)], True)
                 for n in ordered]
    assert checks == want, checks
    heads = [o.text for o in opts if o.type == "desc"][1:]
    assert heads == ["ui_mcm_seasons_zone_yours_own", "ui_mcm_seasons_zone_yours_event",
                     "ui_mcm_seasons_zone_yours_period", "ui_mcm_seasons_zone_yours_spell"]
    main = [pages["main"].gr[i].id for i in range(1, len(pages["main"].gr) + 1)]
    assert "pda_turns" in main, main
    text, _ = calendar(own={}, events={}, periods={}, spells={})
    lua, g = tcal.build(2026, 7, 1, calendar=text)
    op = g.load_in(src, "zzz_seasons_of_the_zone_mcm", g).on_mcm_load()
    assert "yours" not in [op.gr[i].id for i in range(1, len(op.gr) + 1)]
    return "%d switches under 4 headings; none without any" % len(checks)


