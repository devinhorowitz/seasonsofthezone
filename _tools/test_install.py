@case
def t_a_first_install_puts_the_tools_in_the_gamma_folder():
    with tempfile.TemporaryDirectory() as d:
        root, mod = gamma(d)
        rc, out = install(mod, "--yes")
        want = shipped(mod)
        assert rc == 0 and "Installing the tools into your GAMMA folder, %s." % root in out, out
        words = [f for f in os.listdir(os.path.join(HERE, "lang"))
                 if f.endswith(build_release.LANG_FILES)]
        assert len(want) == len(build_release.TOOL_FILES) + 7 + len(words) and \
            "play.bat" in want and os.path.join("_tools", "lang", "ru.po") in want, want
        wrong = [f for f in want if read(root, f) != read(mod, f)]
        assert not wrong, "not there as the zip has them: %s\n%s" % (wrong, out)
        extra = set(snapshot(root)) - set(want) - {
            "ModOrganizer.ini", os.path.join("profiles", "Default", "modlist.txt")}
        assert not extra, "also wrote %s" % sorted(extra)
        assert "Files: %d new." % len(want) in out, out
        assert out.count("    new      ") == len(want), "not every file listed:\n" + out
        assert "From now on, open configure.bat and play.bat in your GAMMA folder" in out, out
    return "%d files, byte for byte, from a mod under MO2's default name; nothing else" % len(
        want)


@case
def t_an_update_keeps_what_is_the_player_s():
    """Tools copied by hand before there was an installer, the player's settings, backups
    and presets beside them, and play.bat set to another of MO2's entries. The tools now
    ship a preset under a name the player used, and a seasons_config.py left in the mod's
    folder must not travel."""
    with tempfile.TemporaryDirectory() as d:
        root, mod = gamma(d)
        old(root, mod)
        winter = os.path.join("_tools", "presets", "Winter.json")
        mine = {os.path.join("_tools", "seasons_config.py"): b"TOGGLE_MODS = {}\r\n",
                os.path.join("_tools", "seasons_config.py.bak"): b"TOGGLE_MODS = {1: 2}\r\n",
                os.path.join("_tools", "seasons_config.py.before-20260901-120000.bak"): b"x",
                os.path.join("_tools", "presets", "Mine.json"): preset(False),
                winter: preset(False)}
        for rel, data in mine.items():
            put(root, rel, data)
        put(mod, winter, preset(True))
        put(mod, os.path.join("_tools", "seasons_config.py"), b"# made here by mistake\r\n")
        put(root, "play.bat", with_entry(read(root, "play.bat"), MINE))
        rc, out = install(mod, "--yes")
        assert rc == 0, out
        assert ("Updating the tools in your GAMMA folder, %s: an older version there, %s "
                "here." % (root, VERSION)) in out, out
        touched = [rel for rel, data in mine.items() if read(root, rel) != data]
        assert not touched, "changed the player's %s:\n%s" % (touched, out)
        stale = [f for f in shipped(mod) if f not in (winter, "play.bat")
                 and read(root, f) != read(mod, f)]
        assert not stale, "not updated: %s\n%s" % (stale, out)
        assert read(root, "play.bat") == with_entry(read(mod, "play.bat"), MINE), \
            "play.bat is not the new one starting %s:\n%s" % (MINE, out)
        assert 'play.bat keeps starting "%s".' % MINE in out, out
        assert "    kept     %s - yours" % winter in out, out
        assert "Files: 2 new, 4 updated, %d the same, 1 of your presets kept." % (
            len(shipped(mod)) - 7) in out, out
        assert "Done. Your settings there are kept." in out, out
    return ("seasons_config.py, 2 backups, 2 presets of the player's and play.bat's entry "
            "kept; 6 tools updated")


