@case
def t_each_file_is_written_whole_or_not_at_all():
    """A file is replaced, not written into: a second name for the old one keeps the old
    bytes. One that can't be replaced is named, the count of those copied is said, and no
    temp file is left behind."""
    with tempfile.TemporaryDirectory() as d:
        root, mod = gamma(d)
        old(root, mod)
        edit = os.path.join("_tools", "config_edit.py")
        was = read(root, edit)
        os.link(os.path.join(root, edit), os.path.join(d, "second name.py"))
        before = snapshot(root)
        todo = [f for f in shipped(mod) if read(root, f) != read(mod, f)]
        stuck = os.path.join(root, SEASON)
        os.chmod(stuck, stat.S_IREAD)
        try:
            rc, out = install(mod, "--yes")
        finally:
            os.chmod(stuck, stat.S_IREAD | stat.S_IWRITE)
        after = snapshot(root)
        wrote = [f for f in after if after[f][0] != before.get(f, (None,))[0]]
        m = re.search(r"(\d+) of the (\d+) files were copied; the rest are as they were", out)
        assert rc == 1 and "Couldn't write %s: " % SEASON in out and m, out
        assert (int(m.group(1)), int(m.group(2))) == (len(wrote), len(todo)), (wrote, out)
        assert after[SEASON] == before[SEASON], "season.py changed"
        assert not [f for f in after if f.endswith(".tmp")], "left a temp file"
        rc, out = install(mod, "--yes")
        assert rc == 0 and all(read(root, f) == read(mod, f) for f in todo), out
        assert read(d, "second name.py") == was, "config_edit.py was written into, not replaced"
    return "replaced whole; a read-only one named, %d of %d copied and said so; the next " \
           "run finishes" % (len(wrote), len(todo))


