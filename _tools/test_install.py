@case
def t_newer_tools_there_are_not_replaced_with_yes():
    """A downgrade is refused from the console. Versions compare as numbers: x.19.0 is
    newer than x.9.0, though it sorts before it as text."""
    major, minor = VERSION.split(".")[:2]
    later = "%s.%d.0" % (major, int(minor) + 10)
    with tempfile.TemporaryDirectory() as d:
        root, mod = gamma(d)
        install(mod, "--yes")
        set_version(root, later)
        put(root, os.path.join("_tools", "config_edit.py"), b"# newer\r\n")
        age(root)
        before = snapshot(root)
        rc, out = install(mod, "--yes")
        assert rc == 1 and "are newer than these: %s there, %s here." % (
            later, VERSION) in out and "Nothing was changed" in out and mod in out, out
        assert snapshot(root) == before, "a refused downgrade changed files"
        # an older VERSION there is an update
        set_version(root, "0.1.0")
        rc, out = install(mod, "--yes")
        assert rc == 0 and "0.1.0 there, %s here." % VERSION in out, out
        assert read(root, SEASON) == read(mod, SEASON), out
    return "%s there refused, nothing changed; 0.1.0 there updated" % later


