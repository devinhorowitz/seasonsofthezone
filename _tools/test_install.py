def t_configure_bat_installs_from_the_mod_s_folder():
    with tempfile.TemporaryDirectory() as d:
        root, mod = gamma(d)
        rc, out = batch(mod, "configure.bat", "--yes")
        assert rc == 0 and "Installing the tools into your GAMMA folder" in out, out
        assert "Press any key" not in out, "paused after an install that went through:\n" + out
        missing = [f for f in shipped(mod) if read(root, f) != read(mod, f)]
        assert not missing, "not installed: %s\n%s" % (missing, out)
        # in the GAMMA folder it runs the tools there, with what follows it passed on
        rc, out = batch(root, "configure.bat", "install", "--yes")
        assert rc == 0 and "The tools already run from your GAMMA folder" in out, out
